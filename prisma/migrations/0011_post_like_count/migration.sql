-- 공감 수 — 그릇
--
-- 이 migration 은 컬럼 하나만 세운다. 화면도 서버 액션도 이 파일에 없다.
-- 적용 직후 모든 글의 likeCount 는 0 이고, 사용자에게 보이는 것은 아무것도 바뀌지 않는다.
--
-- 🔴 세어서 쓰지 않고 컬럼에 담는 이유.
--    Like row 를 매번 세면(_count) 목록에서 행마다 서브쿼리가 붙는다.
--    지금은 상세에만 숫자를 두지만, 세는 방식은 나중에 목록으로 옮길 수 없다 —
--    옮기는 순간 30 행이면 30 번을 센다. 처음부터 담아 둔다.
--
-- 🔴 DEFAULT 0 · NOT NULL 로 둔다.
--    기존 글이 이미 있어 NULL 을 허용하면 "아직 안 센 글" 과 "0 인 글" 이 섞인다.
--    공감은 없으면 0 이다. 모르는 상태가 없다.
--
-- 🔴 backfill 을 하지 않는다.
--    Like 테이블은 스키마에만 있었고 앱이 한 번도 쓰지 않았다
--    (prisma.like 사용처 0 건 — src·agents·scripts 전수 확인).
--    그래서 기존 row 가 없고, 0 이 곧 정답이다.
--    ⚠️ 적용 전에 SELECT COUNT(*) FROM "Like" 로 0 을 확인한다.
--       0 이 아니면 이 migration 뒤에 한 번의 UPDATE 로 맞춘 뒤 진행한다.
--
-- 🔴 index 를 만들지 않는다.
--    likeCount 로 정렬하거나 거르는 화면이 아직 없다. 목록·인기·베스트는 이번에 건드리지 않는다.
--    정렬에 쓰기로 결정한 날 그때 만든다 — 쓰지 않는 index 는 쓰기마다 비용만 낸다.

ALTER TABLE "Post" ADD COLUMN "likeCount" INTEGER NOT NULL DEFAULT 0;
