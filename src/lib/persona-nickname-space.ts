export type NicknameCategory = keyof typeof NICKNAME_LEXICON

/**
 * 🔴 **공간 — 정책을 통과한 이름만, 결정적 순서로.** 갈래를 번갈아 세워(한 갈래에서 하나씩) 앞에서부터 고르면
 *    먹거리만 수십 개가 나란히 붙지 않게 한다. 같은 이름이 두 갈래에 있으면 앞의 것 하나만 남긴다.
 */
export function nicknameSpace(): string[] {
  const lists = Object.values(NICKNAME_LEXICON) as readonly (readonly string[])[]
  const out: string[] = []
  const seen = new Set<string>()
  const longest = Math.max(...lists.map((l) => l.length))
  for (let i = 0; i < longest; i += 1) {
    for (const l of lists) {
      const n = l[i]
      if (n === undefined || seen.has(n)) continue
      seen.add(n)
      if (verifyNamePolicy(n).ok) out.push(n)
    }
  }
  return out
}

/** 🔴 이 이름의 갈래 — 공간 밖이면 null. 고른 이름이 한 갈래로 쏠리는지 볼 때 쓴다 */
export function nicknameCategoryOf(name: string): NicknameCategory | null {
  for (const [k, l] of Object.entries(NICKNAME_LEXICON) as [NicknameCategory, readonly string[]][]) {
    if (l.includes(name)) return k
  }
  return null
}
