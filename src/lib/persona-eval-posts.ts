/** 🔴 프롬프트로 나가는 본문 — 제목·본문·물음을 한 덩어리로 */
export function postBodyOf(p: SyntheticPost): string {
  return p.askedFor.trim() === '' ? p.body : `${p.body}\n${p.askedFor}`
}

/**
 * 🔴 **반응할 거리가 있는가** — 사람이 읽기 전에 기계가 먼저 거른다.
 *    한 줄짜리 입력으로 맥락 적합성을 재는 일이 다시 생기지 않게 한다.
 */
export function judgePostRichness(p: SyntheticPost): { ok: boolean; reason: string } {
  const body = postBodyOf(p)
  const sentences = body.split(/[.!?…\n]+/u).filter((s) => s.trim() !== '').length
  const chars = [...body].length
  if (sentences < 3) return { ok: false, reason: `${p.id}: 문장 ${sentences}개 — 3개 이상이어야 한다` }
  if (chars < 80) return { ok: false, reason: `${p.id}: ${chars}자 — 80자 이상이어야 한다` }
  return { ok: true, reason: `문장 ${sentences} · ${chars}자` }
}
